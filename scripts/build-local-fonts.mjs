// Deterministic resource-only generation; original OFL fonts stay in renderer assets.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const fonts = require('../miniprogram/config/fontFeels.js').FONT_FEELS;
const manifest = {};
const packages = [];
const loaders = [];
const chunkSize = 1280 * 1024;
for (const font of fonts) {
  const file = path.basename(font.fontPath);
  const bytes = fs.readFileSync(path.join(root, 'miniprogram/cloudhosting/fun-card-renderer/assets/fonts', file));
  const parts = [];
  for (let offset = 0, index = 0; offset < bytes.length; offset += chunkSize, index++) {
    const name = 'font-' + font.key + '-' + index;
    const packageRoot = 'font-packages/' + name;
    const directory = path.join(root, 'miniprogram', packageRoot);
    fs.mkdirSync(directory, { recursive: true });
    // Code-package binary reads are denied on some mini program runtimes.
    // Encode inside the async module, then decode without filesystem access.
    const obsoleteBinary = path.join(directory, 'font.ttf');
    if (fs.existsSync(obsoleteBinary)) fs.unlinkSync(obsoleteBinary);
    fs.writeFileSync(path.join(directory, 'entry.js'),
      "// Generated by scripts/build-local-fonts.mjs. Bundled font data, no network or filesystem.\n" +
      "module.exports.read = function (api) {\n" +
      "  return api.base64ToArrayBuffer('" + bytes.subarray(offset, offset + chunkSize).toString('base64') + "');\n};\n");
    fs.writeFileSync(path.join(directory, 'index.js'), 'Page({});\n');
    fs.writeFileSync(path.join(directory, 'index.json'), '{"navigationBarTitleText":"字体资源"}\n');
    fs.writeFileSync(path.join(directory, 'index.wxml'), '<view>字体资源由编辑器自动加载，无需打开此页。</view>\n');
    fs.writeFileSync(path.join(directory, 'index.wxss'), 'view { padding: 32rpx; color: #655d73; }\n');
    packages.push({name, root:packageRoot, pages:['index']});
    loaders.push(JSON.stringify(name) + ": function () { return require.async('../" + packageRoot + "/entry.js'); }");
    parts.push(name);
  }
  manifest[font.key] = {file, bytes:bytes.length, sha256:crypto.createHash('sha256').update(bytes).digest('hex'), parts};
}
fs.writeFileSync(path.join(root, 'miniprogram/config/localFontManifest.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'miniprogram/config/localFontManifest.js'), '// Generated font asset manifest.\nmodule.exports = ' + JSON.stringify(manifest, null, 2) + ';\n');
fs.writeFileSync(path.join(root, 'miniprogram/config/localFontPackages.js'),
  '// Generated static async references for the mini program packager.\nvar loaders = {\n' + loaders.join(',\n') +
  '\n};\nmodule.exports.load = function (name) { return loaders[name](); };\n');
// Preserve unrelated subpackages when regenerating this asset collection.
const appPath = path.join(root, 'miniprogram/app.json');
const app = JSON.parse(fs.readFileSync(appPath, 'utf8'));
app.subPackages = (app.subPackages || app.subpackages || []).filter(p => !p.root.startsWith('font-packages/')).concat(packages);
delete app.subpackages;
fs.writeFileSync(appPath, JSON.stringify(app, null, 2) + '\n');
console.log('Built ' + packages.length + ' font packages; ' + Object.values(manifest).reduce((n,f)=>n+f.bytes,0) + ' font bytes.');
