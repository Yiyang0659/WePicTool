const TARGETS = {
  tops: '上衣：完整保留衣领、双袖、袖口及下摆，去掉裤子和裙子',
  bottoms: '下装：完整保留腰头、裤腿或裙摆，去掉上衣和鞋子',
  shoes: '鞋子：保留原图鞋款及原有单只或成双关系，完整保留鞋头、鞋跟和鞋带，去掉腿部、袜子和裤子'
};

function garmentPrompt(category) {
  if (!TARGETS[category]) throw new Error('不支持的衣物处理分类');
  return '根据用户上传图片制作独立商品展示图，目标仅为' + TARGETS[category] + '。' +
    '移除所有人物、皮肤、脸、脖子、手臂、手、腿、人体模型、衣架、首饰及非目标衣物。' +
    '尽可能忠实保留原商品大致款式、颜色、图案、logo、面料纹理、缝线与比例，不新增装饰，不换款。' +
    '侧拍或局部遮挡时，依据可见款式尽可能补全为自然正面商品形态，不夸大不可见细节。' +
    '背景必须纯白#FFFFFF，不要边框、文字标签、编号、水印或大面积投影。' +
    '完整商品居中，尽量占满画面（约92%），四周少量留白，不裁切边缘、不拉伸。' +
    '浅色衣物保留真实纹理和柔和轮廓，以便在白底上辨认。';
}

module.exports = { garmentPrompt };
